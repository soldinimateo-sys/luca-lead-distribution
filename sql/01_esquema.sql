-- =====================================================================
-- Luca: esquema simplificado (PostgreSQL)
-- Versión reducida del esquema de producción: solo las tablas y columnas
-- necesarias para entender la distribución de leads.
-- =====================================================================

-- Campañas de venta (cada lead y cada operador pertenece a una)
CREATE TABLE sale_campaigns (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           varchar(100) NOT NULL UNIQUE,
    business_line  varchar(20)  NOT NULL,                 -- 'datos' | 'movil'
    state          varchar(20)  NOT NULL DEFAULT 'activo'  -- 'activo' | 'inactivo'
);

-- Operadores del call center
CREATE TABLE operators (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              varchar(80) NOT NULL UNIQUE,
    active            boolean     NOT NULL DEFAULT true,
    shift             varchar(4)  NOT NULL,     -- 'AM' | 'PM' | 'FULL'
    business_line     varchar(20) NOT NULL,     -- 'datos' | 'movil'
    interface         varchar(10) NOT NULL,     -- 'sheet' | 'luca' | 'odoo'
    sale_campaign_id  bigint REFERENCES sale_campaigns(id)
);

-- Leads: clientes a contactar. Los datos de contacto viven acá;
-- el ESTADO no se guarda en esta tabla (ver lead_events).
CREATE TABLE leads (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rango             varchar(20) UNIQUE,        -- identificador del contrato
    landline          varchar(20) NOT NULL DEFAULT '',
    mobilephone       varchar(20) NOT NULL DEFAULT '',
    contract_exp      date,                      -- vencimiento del contrato
    date_added        timestamptz NOT NULL DEFAULT now(),
    no_me_llame       varchar(20) NOT NULL DEFAULT 'sin_chequear'
                      CHECK (no_me_llame IN ('sin_chequear', 'no_esta', 'esta')),
    sale_campaign_id  bigint REFERENCES sale_campaigns(id)
);
CREATE INDEX ON leads (contract_exp);

-- Cada corrida del reparto
CREATE TABLE distributions (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_time      timestamptz NOT NULL,
    shift          varchar(2)  NOT NULL,         -- 'AM' | 'PM'
    business_line  varchar(20) NOT NULL
);
CREATE INDEX ON distributions (date_time);

-- Log de eventos: cada cambio de estado de un lead es una fila nueva.
-- Por convención solo se inserta (append-only): nunca se actualiza el estado
-- en el lugar. El estado actual es el último evento; cualquier estado pasado
-- se puede reconstruir.
CREATE TABLE lead_events (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id          bigint      NOT NULL REFERENCES leads(id),
    date_time        timestamptz NOT NULL,
    channel          varchar(10) NOT NULL,       -- 'call' | 'wpp' | 'system'
    new_state        varchar(30) NOT NULL,
    -- call/system: disponible, nuevo, no_contesta, a_y_c, agendado, en_tramite,
    --              venta, rechazo, renovado, sin_servicio, retirado
    distribution_id  bigint REFERENCES distributions(id),  -- si el evento lo generó un reparto
    operator_id      bigint REFERENCES operators(id)
);
CREATE INDEX ON lead_events (lead_id, channel, date_time DESC);
CREATE INDEX ON lead_events (channel, new_state);
CREATE INDEX ON lead_events (distribution_id);
